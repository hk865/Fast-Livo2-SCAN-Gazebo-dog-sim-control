def state_bits(value):
    if isinstance(value,np.ndarray):return ('array',str(value.dtype),value.shape,value.tobytes().hex())
    if isinstance(value,(float,np.floating)):return ('float64',struct.pack('>d',float(value)).hex())
    if isinstance(value,dict):return {k:state_bits(v)for k,v in value.items()}
    if isinstance(value,(list,tuple)):return [state_bits(v)for v in value]
    return value


